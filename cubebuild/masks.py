"""uint8 validity-mask companion mechanism (reused by all layers with missing values).

Mechanism (the missing-value system):
- Float data layers: missing = NaN; the companion mask layer <layer_id>__validity is generated
  in the same tier as the data layer, with the same shape/coordinates, uint8: 1 = valid, 0 = missing;
- Integer categorical layers: class codes start at 1, 0 = no class/missing,
  mask determination = data != 0 (the single implementation, data_missing);
- The manifest layer entry's validity_mask field links the data layer ↔ the mask layer (generated by manifest.py);
- Structure validation applies the hard criterion "missing ⟺ mask 0" as a two-channel consistency check (validate.py).

Mask semantics = the data layer is non-missing: isfinite for float layers; non-zero for integer categorical layers. A partially covered
pixel (≥1 valid subcell means a value in a vector-rasterization block) is marked 1 — the same semantics as the conservative kernel's "W>0 means
a value" (see kernels.conservative_overlap_mean / aggregate_mode).
Whether a companion layer is needed is determined by the contract mask field (the single determination, contract.needs_validity_mask).
"""

import numpy as np
import xarray as xr

from .contract import LayerEntry

VALIDITY_SUFFIX = "__validity"


def data_missing(data, zero_is_missing: bool = True):
    """Missing-value determination for a data-layer array (the single implementation for float NaN / integer-class 0).

    Float layers: NaN; integer layers (class codes start at 1, e.g. vector-rasterized categorical layers):
    0 = no class/missing. Both the build side (build_validity_mask) and the validation side
    (validate.py's two-channel consistency hard criterion) share this function, ensuring the two sides use the same criterion.

    zero_is_missing=False: the form where an integer layer's 0 is a real class (e.g. the land-sea mask
    0=sea, contract mask=itself i.e. the mask, with no validity companion layer) — here the integer
    layer has no missing values. The caller decides per the contract's needs_validity_mask (cli coverage).
    """
    if np.issubdtype(data.dtype, np.floating):
        return data.isnull()
    if zero_is_missing:
        return data == 0
    return data.isnull()


def validity_layer_name(layer_id: str) -> str:
    """Data-layer id → companion mask layer name (the store-wide single convention)."""
    return f"{layer_id}{VALIDITY_SUFFIX}"


def build_validity_mask(data: xr.DataArray, entry: LayerEntry) -> xr.DataArray:
    """Data-layer array → uint8 validity companion layer (lazy: dask input → dask output).

    The two-channel consistency (missing ⟺ mask 0) is a structure-validation hard criterion,
    and this function is the single source of the mask values (not hand-written elsewhere).
    """
    mask = (~data_missing(data)).astype(np.uint8)
    mask.name = validity_layer_name(entry.id)
    mask.attrs = {
        "units": "1",
        "long_name": "有效性掩膜（1=有效，0=缺测）",
        "source": entry.source,
        "validity_of": entry.id,
        "visibility": entry.visibility,
    }
    return mask
