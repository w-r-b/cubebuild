"""4D paleo-elevation channel: Scotese & Wright 2018 PaleoDEM.

Source contract (disk-verified, a full scan of 109 slices × 2 products, with coordinates/value ranges/missing values/seams
all checked on the actual machine):

- paleodem-6min-nc (109 slices): 1801×3601 gridline node registration, latitude 90→-90
  north-first descending, longitude -180→180; variable z float32; no NaN anywhere (0 missing across 109 slices
  — paleogeography is encoded numerically: negative = paleo-ocean depth, 0 = sea level, positive = paleo-land-surface elevation, so missing-value
  semantics do not apply, validity mask all 1); value range [-11000, 10500] m. The ±180 two columns have different values
  (per-slice max difference up to 14620 m) — independent sampling on the two sides of the seam (isomorphic to GLAD: the dateline seam of the paleogeographic
  conversion grid), with internal continuity symmetric (|179.9−180| median 40 m vs.
  |-179.9−(-180)| median 120 m), so neither can be discarded in favor of the other.
- paleodem-1deg-nc (109 slices): 181×361 node registration, lat -90→90 ascending, lon
  -180→180; z float32 with no NaN, value range [-9000, 10500] m. The ±180 two columns are **bit-identical**
  (seam difference exactly 0 across 109 slices) — the official 1° product is generated by GMT grdsample, which samples the
  -180 column when periodic (measured: the 1° ±180 columns == the 6min -180 column, all 180/180 sampled rows match).
- time axis = the filename Ma label (regex _(\\d+(?:\\.\\d+)?)Ma\\.nc$), each product 109
  slices, (after 1° alignment) strictly ascending and unique, 0–540 Ma; the two 1° slices (Map67.5/68, source filenames
  385.2/390.5 Ma) are rounded to 385/390 per the official integer naming convention (the official
  two-track naming — integer coarse labels in filenames are the system convention (85 of the 109 6min slices ≠ the internal
  description exact age; the 6min Map67.5/68 filenames are 385/390, the internals 385.2/390.5
  Ma), while the two exactly-named 1° slices are the outliers; the officials' own rounding convention: Map54 internal 286.8
  → filename 285) — the two tiers' label sets agree value by value 109/109, so cross-tier chronological use aligns directly.
  Filename lexicographic order ≠ Ma order (Map43.5_205Ma precedes Map43_200Ma), so sorting must be by the
  parsed value; cross-tier alignment is by label value, not Map sheet number (near the Guadalupian the two tiers'
  numbers are offset by half a slot: 6min Map53.5@280/Map54@285 ↔ 1° Map54@280/Map54.5@285,
  aligning by number would be offset).

Registration (registration_rule): both products use gridline node registration →
Voronoi cell interpretation (the nodes are point samples of the field, the Voronoi cells are the minimum-bias discretization of the conservative mean);
6min tier: the ±180 seam's two columns are averaged (symmetrized conservative) and the +180 column dropped → (1801, 3600), fed by
conservative_overlap_mean into the cube 6min tier (the source cell 0.1° and target cell 0.1° are offset by half a cell
→ target cell = area-weighted mean of adjacent nodes, i.e. the registration interpretation of the native-resolution tier rather than tier
aggregation, same as the GLAD 1° tier); 1° tier: the official 1° product is read directly (no downsampling), ±180
bit-identical so the +180 column is dropped → (181, 360), fed by the Voronoi conservative kernel into the cube 1° tier (same
geometry as GLAD).

Write structure: the [time, lat, lon] 4D array differs in shape from the tier node's 2D layers → it goes into the tier subnodes
/6min/paleodem and /1deg/paleodem (group-node mechanism; manifest datatree_node
records the relative group name, validate resolves as /{tier}/{group}); time is chunked per slice
(6min (1,900,900) / 1deg (1,180,360)) enabling a downstream single .sel(time=) to take any
geological-age slice.

Thread safety: the source is HDF5 (netCDF4), not thread-safe → the module-level read lock guards only file I/O,
with the numpy kernels running in parallel outside the lock (build determinism is unaffected under the dask threaded scheduler: the kernels are einsum
single-threaded reductions).
"""

